const PNG = Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]);
const sha256 = (b) => createHash('sha256').update(b).digest('hex');
// Expected shape: choices 1:1; question and narration pictures 4:3; S3.N2 is a 16:9 strip.
const expectedRatio = (id) => (id === 'S3.N2' ? 16 / 9 : /\.c\d+$/.test(id) ? 1 : 4 / 3);

async function main() {
  const i = process.argv.indexOf('--base');
  const base = i > 0 ? process.argv[i + 1] : '';
  if (!/^https:\/\//.test(base)) throw new Error('usage: npm run assets:images -- --base <https url ending in />');
  const entries = [];
  for (const [recordId, filename] of Object.entries(IMAGES)) {
    const stationId = recordId.split('.')[0];
    const res = await fetch(new URL(filename, base));
    if (!res.ok) throw new Error(`${recordId}: HTTP ${res.status}`);
    const original = Buffer.from(await res.arrayBuffer());
    if (!original.subarray(0, 8).equals(PNG)) throw new Error(`${recordId}: not a PNG`);
    const outPath = `images/${stationId}/${recordId}.webp`;
    mkdirSync(path.join(ROOT, 'public', 'images', stationId), { recursive: true });
    const { data, info } = await sharp(original).resize({ width: 1200, withoutEnlargement: true }).webp({ quality: 82 }).toBuffer({ resolveWithObject: true });
    writeFileSync(path.join(ROOT, 'public', outPath), data);
    const ratio = info.width / info.height;
    const shapeOk = Math.abs(ratio - expectedRatio(recordId)) / expectedRatio(recordId) < 0.06;
    entries.push({ recordId, path: `/${outPath}`, width: info.width, height: info.height, bytes: data.length, source: SOURCE, originalFilename: filename, originalSha256: sha256(original), webpSha256: sha256(data) });
    console.log(`${recordId}: ${info.width}x${info.height} ${Math.round(data.length / 1024)} KB${shapeOk ? '' : ` (shape ${ratio.toFixed(2)}:1, expected ${expectedRatio(recordId).toFixed(2)}:1)`}`);
  }
  const doc = {
    note: 'Station pictures (S1-S3). Converted with sharp: WebP quality 82, aspect ratio kept, max width 1200. Generated by npm run assets:images.',
    images: entries,
  };
  writeFileSync(path.join(ROOT, 'public', 'images', 'IMAGES.json'), `${JSON.stringify(doc, null, 2)}\n`);
  console.log(`total: ${entries.length} images, ${Math.round(entries.reduce((n, e) => n + e.bytes, 0) / 1024)} KB`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === import.meta.filename) await main();
